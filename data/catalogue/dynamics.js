//   fe fear (of you), ri rivalry, sh shame, dv devotion, rt restraint, sw sway (you can steer them),
//   cm complicity, uw unworthiness, pa pushing away, ex exasperation, hi shared past, sc sacrifice,
//   os thinks it's mutual (low = sure it's one-sided), cr crudeness, pt paternalism, gr grooming, pl playfulness, pi pride in them,
//   fm ease, ts testing (1.78);
//   ds is the Desire card's heat.
// Every row whose test passes is a candidate. Earlier rows are more specific and score higher, and what's on
// the cards (moods, ties, a mood clash, words in the latest replies) lifts the ones that fit (bond.js
// dynamicOf), so the same meters can read differently in different scenes.
