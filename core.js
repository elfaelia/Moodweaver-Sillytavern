export const tierOf = v => TIERS.find(t => v >= t.min) ?? null;
function moodPhrase(m, compact) {
    const [name, gloss, keep] = GLOSS[m.id] ?? [];
    const label = name ?? m.label.toLowerCase();
    return gloss && (!compact || keep) ? `${label} (${gloss})` : label;
}
export function composePrompt(state, name, compact = false) {
    if (!state.enabled || !activeMoods(state).length) return '';
    const active = activeMoods(state);
    const n = String(name ?? '').trim() || 'the character';
    const tiers = TIERS.map(t => ({ t, list: active.filter(m => tierOf(state.moods[m.id]) === t) })).filter(x => x.list.length);
    const lines = [
        `Mood settings the user has chosen for ${n}: what ${n} is feeling going into this reply, strongest first. Strength works as it does in a real person. The fainter a feeling, the less it shows and the more easily the situation, ${n}'s personality and their judgement override it. The stronger it is, the more it takes over.`,
        '',
        ...tiers.flatMap(({ t, list }) => [`${t.name}: ${list.map(m => moodPhrase(m, compact)).join(', ')}`, t.text, '']),
        `All of these are felt at once and blend into one inner life, the way real emotions overlap. Stronger feelings lead and weaker ones tint them. Contradictory feelings become tension or mixed feelings rather than cancelling out. How much shows depends on who ${n} is, who else is present and what is at stake: a secret, public or risky situation keeps milder feelings private, while strong ones strain against it. Feelings not listed here come from the scene as usual.`,
    ];
    if (active.some(m => m.category === 'appetites')) lines.push(`The dynamics listed are what ${n} is drawn toward, not an arrangement that already exists; they come out as far as the relationship and the scene allow.`);
    if (state.sceneBreathing !== false) lines.push(`Let the current activity and conversation run at their own pace. The mood changes how ${n} takes part; only a feeling strong enough to derail things should change the scene's direction.`);
    lines.push(`Show all of this through ${n}'s thoughts, voice and behaviour while keeping them in character. Don't mention these settings or strength levels in the reply.`);
    return `<mood_settings character="${escapeHtml(n)}">\n${lines.join('\n')}\n</mood_settings>`;
}
export async function budgetPrompt(state, name, budget, countTokens) {
    const all = state.enabled ? activeMoods(state) : [];
    let prompt = composePrompt(state, name);
    let tokens = prompt ? await countTokens(prompt) : 0;
    let compact = false;
    if (tokens > budget) { compact = true; prompt = composePrompt(state, name, true); tokens = prompt ? await countTokens(prompt) : 0; }
    // The target trims optional explanations, never user-selected values or blend rules.
    // Report overruns explicitly instead of silently changing the requested character.
    return { prompt, tokens, compact, overBudget: Math.max(0, tokens - budget), target: budget,
        selectedIds: all.map(m => m.id), omittedIds: [], omitted: 0 };
}
export function parseAnalysis(text) {
    const clean = String(text).trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '');
    let data;
    try { data = JSON.parse(clean); } catch { throw new Error('The analyser did not return valid JSON. Your moods were kept.'); }
    if (!data || typeof data.moods !== 'object' || Array.isArray(data.moods) || data.moods === null) throw new Error('The analyser returned no mood object. Your moods were kept.');
    const moods = {};
    for (const [id, value] of Object.entries(data.moods)) {
        if (!Object.hasOwn(BY_ID, id)) continue;
        if (typeof value !== 'number' || !Number.isFinite(value) || value < 0 || value > 100) throw new Error('The analyser returned an invalid intensity. Your moods were kept.');
        moods[id] = Math.round(value);
    }
    if (Object.keys(data.moods).length && !Object.keys(moods).length) throw new Error('The analyser returned unknown moods. Your moods were kept.');
    return { moods, reason: typeof data.reason === 'string' ? data.reason.slice(0, 240) : '' };
}
export function blendAnalysis(state, result) {
    const next = { ...state.moods };
    const responsiveness = 1 - state.inertia / 100;
    const maxStep = 5 + state.sensitivity * .3;
    for (const m of MOODS) {
        if (state.pins[m.id]) continue;
        const old = state.moods[m.id] || 0;
        // Absence gently fades a state; an explicit zero can resolve it faster.
        const target = Object.hasOwn(result.moods, m.id) ? result.moods[m.id] : Math.max(0, old - state.decay);
        const scaled = Object.hasOwn(result.moods, m.id) ? clamp(target * (.5 + state.sensitivity / 100)) : target;
        let delta = clamp((scaled - old) * responsiveness, -maxStep, maxStep);
        if (delta !== 0 && Math.abs(delta) < 1) delta = Math.sign(delta);
        next[m.id] = Math.round(clamp(old + delta));
    }
    return next;
}
export function sceneData(chat, character, state, settings) {
    const visible = chat.filter(m => !m.is_system && typeof m.mes === 'string');
    let remaining = settings.sceneChars;
    const scene = [];
    for (const m of visible.slice(-settings.sceneMessages).reverse()) {
        if (remaining <= 0) break;
        const text = m.mes.slice(-remaining);
        scene.unshift({ speaker: String(m.name ?? (m.is_user ? 'User' : 'Character')).slice(0, 100), text });
        remaining -= text.length;
    }
    return { character: { name: String(character?.name ?? '').slice(0, 100),
        personality: String(character?.personality ?? character?.data?.personality ?? '').slice(0, 1600),
        description: String(character?.description ?? character?.data?.description ?? '').slice(0, 2400) },
    previous_moods: Object.fromEntries(activeMoods(state).map(m => [m.id, state.moods[m.id]])),
    pinned: Object.keys(state.pins).filter(k => state.pins[k]), scene };
}
