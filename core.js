// Add catalogue entries to old chats in place, preserving their history and settings.
export function extendCatalogue(state) {
    state.sceneBreathing ??= true;
    state.moods ??= {};
    state.pins ??= {};
    for (const { id } of MOODS) {
        state.moods[id] ??= 0;
        state.pins[id] ??= false;
    }
    return state;
}
